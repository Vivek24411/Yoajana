export type Locale = (typeof LOCALES)[number];
export const hasLocale = (l: string): l is Locale => (LOCALES as readonly string[]).includes(l);

/** Fill "{n} schemes" style templates. Dictionaries cross the server/client boundary, so they hold strings, not functions. */
export const fmt = (s: string, vars: Record<string, string | number>) =>
  s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ""));

/** Section numbers: "०२" in Hindi, "02" in English. */
export const numeral = (n: number, lang: Locale, pad = 2) =>
  String(n).padStart(pad, "0").replace(/\d/g, (d) => (lang === "hi" ? "०१२३४५६७८९"[Number(d)] : d));

